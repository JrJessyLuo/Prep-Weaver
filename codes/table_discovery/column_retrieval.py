# Entry point
# ============================================================

def build_keyword_column_similarity(
    paths: "P.Paths",
    embedding_model_name: str = "WhereIsAI/UAE-Large-V1",
    llm_model: str = "gpt-4.1",
    batch_size: int = 64,
    top_k: int = 100,
    limit: int = 0,
    force_regenerate_keywords: bool = False,
    force_recompute_column_embeddings: bool = False,
    force_recompute_keyword_embeddings: bool = False,
):
    """Run stage 1 end to end for one dataset.

    limit > 0 keeps only the first N questions, which is what the smoke test
    uses to bound the number of LLM calls.
    """
    dev = read_json(str(paths.dev))
    tables = read_json(str(paths.tables))

    if limit and limit > 0:
        dev = dev[:limit]
        print(f"[stage1] limited to the first {len(dev)} questions")

    out_dir = str(paths.out_dir)
    create_directory(out_dir)
    keyword_path = os.path.join(out_dir, "question_keywords.json")

    # 1. Decompose each question into keyphrases (the only LLM call here).
    question_keywords = extract_keywords_for_dev(
        dev=dev,
        out_path=keyword_path,
        model=llm_model,
        force_regenerate=force_regenerate_keywords,
    )

    # 2. Embed the column corpus (cached).
    column_ids, column_meta, column_embeds = get_or_build_column_embeddings(
        tables=tables,
        out_dir=out_dir,
        model_name=embedding_model_name,
        batch_size=batch_size,
        force_recompute=force_recompute_column_embeddings,
    )
    print(f"Column embedding shape: {tuple(column_embeds.shape)}")

    # 3. Retrieve the top-k columns for every keyphrase.
    keyword_to_top_columns, question_level_results = retrieve_topk_columns_for_keywords(
        question_keywords=question_keywords,
        column_meta=column_meta,
        column_embeds=column_embeds,
        out_dir=out_dir,
        model_name=embedding_model_name,
        batch_size=batch_size,
        top_k=top_k,
        force_recompute_keyword_embeddings=force_recompute_keyword_embeddings,
    )

    return {
        "question_keywords": question_keywords,
        "column_ids": column_ids,
        "column_meta": column_meta,
        "keyword_to_top_columns": keyword_to_top_columns,
        "question_level_results": question_level_results,
        "out_dir": out_dir,
    }


def parse_args():
    parser = argparse.ArgumentParser(
        description="Stage 1: keyphrase extraction + keyphrase-column retrieval.")
    P.add_arguments(parser)
    parser.add_argument("--top-k", type=int, default=100,
                        help="Columns retrieved per keyphrase. Also the N in the "
                             "question_keywords_top{N}_columns.json file name.")
    parser.add_argument("--embedding-model", type=str, default="WhereIsAI/UAE-Large-V1",
                        help="Sentence encoder used for columns and keyphrases.")
    parser.add_argument("--llm-model", type=str, default="gpt-4.1",
                        help="LLM used for keyphrase extraction.")
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--limit", type=int, default=0,
                        help="Only process the first N questions (0 = all). "
                             "Use it to bound LLM cost in a smoke test.")
    parser.add_argument("--force-regenerate-keywords", action="store_true")
    parser.add_argument("--force-recompute-column-embeddings", action="store_true")
    parser.add_argument("--force-recompute-keyword-embeddings", action="store_true")
    return parser.parse_args()


if __name__ == "__main__":
    a = parse_args()
    build_keyword_column_similarity(
        P.from_args(a),
        embedding_model_name=a.embedding_model,
        llm_model=a.llm_model,
        batch_size=a.batch_size,
        top_k=a.top_k,
        limit=a.limit,
        force_regenerate_keywords=a.force_regenerate_keywords,
        force_recompute_column_embeddings=a.force_recompute_column_embeddings,
        force_recompute_keyword_embeddings=a.force_recompute_keyword_embeddings,
    )
