"""Stage 1: fine-grained keyphrase -> column retrieval.

Input  (profiles/): dev.json, dev_tables.json
Output (results/):  question_keywords.json
                    question_keywords_top{N}_columns.json
                    column_embeddings.pt / column_ids.json / column_meta.json
                    keyword_embeddings.pt / unique_keywords.json

Two sub-steps:

  1. An LLM decomposes each question into non-composite noun concepts and
     attributes ("keyphrases"). Cached in question_keywords.json and written
     after every question, so an interrupted run resumes for free.
  2. Every column of the collection is embedded as "TABLE_NAME COLUMN_NAME"
     with a sentence encoder, every keyphrase is embedded the same way, and
     the top-N most similar columns per keyphrase are stored. Both embedding
     sets are cached, so re-running without --force-* costs nothing.

Only sub-step 1 calls an LLM; sub-step 2 runs locally on CPU, MPS or CUDA.

Run:
    python -m table_discovery.column_retrieval --dataset Beaver-Prep --top-k 100
"""

