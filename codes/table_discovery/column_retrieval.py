# ============================================================
# Prompt for keyword/concept extraction
# ============================================================

COTD_FEW_SHOT = """I'm going to ask you a question. I want you to decompose it into a series of non-composite noun concepts and attributes. If you are uncertain about concepts, only output attributes. You should wrap each concept and attribute in <sub_c></sub_c> tags. Once you have all the concepts you need to cover the question, output <FIN></FIN> tags.

Follow these rules strictly:
1. PRESERVE every modifier/qualifier that appears in the question. Do NOT generalize. For example, keep "HR department name" as is — do NOT shorten it to "department name". Keep "gross square footage", "assignable area", "facility organization" with their modifiers.
2. Use the form entity:attribute ONLY when the entity that OWNS the attribute is explicitly named in the question. Do NOT prepend the entity that is merely the subject being queried, a container, or the context. For "the organization name of each room", output "organization:name", NOT "room:organization name". For "the square footage of rooms", output "room:square footage", but for "total square footage" with no owner, output just "square footage".
3. Never convert a mentioned entity into an aggregate or a count. Counts, totals, numbers-of, and averages are OPERATIONS, not concepts. If the question says "the organizations occupying them" or "number of organizations", output the concept "organizations" — NOT "organization:count" or "building:number of organizations".
4. When the question already gives a clean noun phrase for the concept, output that noun phrase faithfully rather than re-bucketing it under an unrelated entity.

Let's go through some examples together. Do you understand the instructions?

Assistant: Yes, I understand. I will decompose questions into faithful noun concepts and attributes, preserve all qualifiers, only use entity:attribute when the owning entity is explicitly named, and never turn a mentioned entity into a count/aggregate. I'll wrap each component in <sub_c></sub_c> tags and finish with <FIN></FIN>.

Human: Question: For movies with the keyword of \"civil war\", calculate the average revenue generated by these movies.

Assistant:
<sub_c>movies:keyword</sub_c>
<sub_c>movies:revenue</sub_c>
<FIN></FIN>

Human: Question: How many customers have a credit limit of not more than 100,000 and which customer made the highest total payment amount for the year 2004?

Assistant:
<sub_c>customers:credit limit</sub_c>
<sub_c>customers:payment amount</sub_c>
<sub_c>year</sub_c>
<FIN></FIN>

Human: Question: What is the aircraft name for the flight with number 99?
Assistant:
<sub_c>aircraft:name</sub_c>
<sub_c>flight:number</sub_c>
<FIN></FIN>

Human: Question: List the building names and the HR department name occupying them, and the number of organizations per building.
Assistant:
<sub_c>building:name</sub_c>
<sub_c>HR department name</sub_c>
<sub_c>organizations</sub_c>
<FIN></FIN>

Human: Question: For each room, show its organization name, the floor number, and the total square footage.
Assistant:
<sub_c>organization:name</sub_c>
<sub_c>floor number</sub_c>
<sub_c>square footage</sub_c>
<FIN></FIN>

Human: Question: What is the id of the trip that started from the station with the highest dock count?
Assistant:
<sub_c>trip:id</sub_c>
<sub_c>station:dock count</sub_c>
<FIN></FIN>
"""


