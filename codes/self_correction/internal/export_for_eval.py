_TABLE = '''
# ---- {lt} (from {input_file}) ----
_spec_{n} = {spec}
_steps_{n} = {steps}
{var} = _prep(_source({src!r}, {path!r}), _spec_{n})
{var} = _apply({var}, _spec_{n}, _steps_{n})
{var} = _finish({var}, _spec_{n})
result[{lt!r}] = {var}
'''

# A table `revise_pipeline` rewrote. It replaces _TABLE rather than following
# it: the loop built this frame from the RAW input, not from the synthesis
# chain, so emitting both would apply the operators twice.
_REWRITTEN = '''
# ---- {lt} (from {input_file}) — repaired by revise_pipeline, base={base} ----
_spec_{n} = {spec}
_steps_{n} = {steps}
{var} = _source({src!r}, {path!r})
{replay}{code}{var} = _finish({var}, _spec_{n})
result[{lt!r}] = {var}
'''

_JOIN = '''
# ---- declared join edge: {lt}.{lo} <-> {rt}.{ro} ----
# The trace records join keys ONLY from an actual merge/isin/map call, so this
# has to run even though the pipeline itself stops before joining.
#
# Retry on a string-cast of both key columns. pandas refuses to merge an int64
# column against an object one even when the values coincide, and swallowing
# that ValueError scored the edge as if no key existed: bird_dcfac5a0 joins
# statusId (int64, '61'/'1'/'62') to status_id (object, '1'/'2'/'3') and was
# marked 0.33 instead of 1.0. Casting is a genuine key-alignment step any real
# system performs, not a scoring trick — a wrong key (bird_9f80c2ab pairs a
# region NAME with a numeric district_id) still fails to overlap after the cast.
try:
    _j{n} = _trace_join({lvar}, {rvar}, {lo!r}, {ro!r})
except Exception:
    try:
        _l{n} = {lvar}.assign(**{{{lo!r}: {lvar}[{lo!r}].astype(str)}})
        _r{n} = {rvar}.assign(**{{{ro!r}: {rvar}[{ro!r}].astype(str)}})
        _j{n} = _trace_join(_l{n}, _r{n}, {lo!r}, {ro!r})
    except Exception:
        pass
'''


def _var(lt: str) -> str:
    return "_" + re.sub(r"[^0-9a-zA-Z_]", "_", lt)


def render_task(pipeline: Dict[str, Any],
                input_files: Dict[str, str],
                specs: Dict[str, dict],
                bench_dir: Path = BENCH_DIR) -> str:
    """Render one task's pipeline as an executable module.

    `pipeline["rewrite"]`, when present, maps a logical table to what
    `revise_pipeline` did to it — `{"base": "raw"|"replay", "steps": [...],
    "code": "<transform(df) snippet>"}` — and REPLACES that table's operator
    chain, because the loop built it from the raw input rather than from the
    chain.
    """
    parts = [_HEADER.format(task_id=pipeline.get("task_id"),
                            question=str(pipeline.get("question") or "").replace('"""', "'''"),
                            train=str(TRAIN), peval=str(TRAIN),
                            putils=str(TRAIN))]

    tables = pipeline.get("tables") or {}
    rewrites = pipeline.get("rewrite") or {}
    emitted: Dict[str, str] = {}
    for n, (lt, t) in enumerate(sorted(tables.items()), start=1):
        f = input_files.get(lt)
        if not f:
            continue
        rw = rewrites.get(lt)
        if rw is not None:
            var = _var(lt)
            parts.append(_REWRITTEN.format(
                n=n, lt=lt, var=var, input_file=f, base=rw.get("base"),
                src=_tracer_name(lt, input_files), path=str(bench_dir / f),
                spec=_lit(specs.get(lt) or {}),
                steps=_lit(rw.get("steps") or []),
                replay=(f"{var} = _replay({var}, _steps_{n})\n"
                        if rw.get("base") == "replay" else ""),
                code=(f"_code_{n} = {rw['code']!r}\n"
                      f"{var} = _rewrite({var}, _code_{n})\n"
                      if rw.get("code") else "")))
            emitted[lt] = var
            continue
        parts.append(_TABLE.format(
            n=n, lt=lt, var=_var(lt),
            src=_tracer_name(lt, input_files),      # None -> load from path
            path=str(bench_dir / f),
            input_file=f,
            spec=_lit(specs.get(lt) or {}),
            steps=_lit(t.get("steps") or []),
        ))
        emitted[lt] = _var(lt)

    for n, e in enumerate(pipeline.get("join_keys") or [], start=1):
        lt, rt = e.get("left_table"), e.get("right_table")
        if lt in emitted and rt in emitted:
            parts.append(_JOIN.format(n=n, lt=lt, rt=rt, lvar=emitted[lt],
                                      rvar=emitted[rt],
                                      lo=e.get("left_on"), ro=e.get("right_on")))
    return "".join(parts)


def _tracer_name(lt: str, input_files: Dict[str, str]) -> Optional[str]:
    """The `table_N` key the TRACER will use for this logical table.

    The evaluator builds its namespace by enumerating `rec["input_table"]` in
    benchmark order, so the Nth input file is always `table_N` there — regardless
    of how the plan numbered its logical tables. Since 22 of the 43 plans permute
    that numbering, resolving through the file name is the only correct mapping;
    using the logical name directly would silently feed half the tasks the wrong
    frame, which is exactly the bug this exporter had to fix upstream.
    """
    f = input_files.get(lt)
    if not f:
        return None
    return _FILE_TO_TRACER.get(f)      # None when the file is not in input_table


_FILE_TO_TRACER: Dict[str, str] = {}


def _lit(obj: Any) -> str:
    """Repr that survives round-tripping into generated source."""
    return repr(json.loads(json.dumps(obj, default=str)))


