# Schema conformance runs in `pipeline_synthesize` AFTER the operator loop, on the
# selected frames — it is not one of the recorded `steps`, so replaying the steps
# alone reproduced the PRE-conform tables. That made the whole pass invisible to
# `eval_all_oom`, which reads these scripts, while `score_subtables` (reading
# tables.pkl) saw it: measured on the spider forward run, the exported script
# emitted `author_id = '"0"'` where tables.pkl held `'0'`. Two scorers, two
# different answers, from the same run.
try:
    from schema_conform import conform_to_schema as _conform
except Exception:      # the eval sandbox may not expose actions/ on sys.path
    _conform = None


def _finish(df, spec):
    """Apply schema conformance exactly where the pipeline applies it."""
    import os as _os
    if _conform is None or _os.environ.get("CONFORM_SCHEMA") != "1":
        return df
    try:
        return _conform(df, (spec or {{}}).get("column_types") or {{}})
    except Exception:
        return df


# Estimated CELLS (rows x combined width), not rows: what kills the process is
# memory, and the two are not interchangeable. spider peaks at 240M cells across
# a 21.8M-row join of very narrow tables and must not be touched; the beaver join
# that gets SIGKILLed is ~1.1B cells (15.4M rows x ~74 columns). A row-based cap
# would have fired on 4 spider tasks for no reason.
_JOIN_CELL_CAP = 400_000_000


def _trace_join(l, r, lo, ro):
    """Run the declared join so the tracer records its key value domains.

    The merged frame is never read downstream — only the tracer's view of the
    key columns is scored. When the join would explode, merging the DEDUPLICATED
    key columns alone records exactly the same key value domains (the scorer
    normalises each domain to a set, so row multiplicity is invisible) while
    bounding memory by the number of distinct keys.

    Below the cap the original full merge runs untouched, so any benchmark whose
    joins stay under it is byte-identical — this is a blow-up guard, not a
    change of semantics. Beaver needs it: beaver-4a769c64 joins a 58k-row fact
    table against a 20k-row one on a low-cardinality code column and the process
    is SIGKILLed at the evaluator's 8 GB limit, scoring 0 on a task the method
    had actually solved. 23 of 119 beaver tasks died this way; every baseline
    lost at most 2.
    """
    try:
        vl = l[lo].value_counts()
        vr = r[ro].value_counts()
        common = vl.index.intersection(vr.index)
        rows = int((vl.reindex(common) * vr.reindex(common)).sum()) if len(common) else 0
        est = rows * (l.shape[1] + r.shape[1])
    except Exception:
        est = None                      # unhashable/exotic dtype: take the normal path
    if est is not None and est > _JOIN_CELL_CAP:
        l = l[[lo]].drop_duplicates()
        r = r[[ro]].drop_duplicates()
    return l.merge(r, left_on=lo, right_on=ro, how="inner")


def _source(tracer_key, path):
    """The raw frame for one logical table.

    The evaluator seeds its namespace from `rec["input_table"]` only. beaver and
    realdp tasks are posed over `retrieved_table`, and on those benchmarks NO
    task's retrieved set is a subset of input_table (0 of 119 beaver tasks; 495
    table references would simply be absent), so `tables[...]` cannot supply
    them. Read from disk in that case. Frames loaded here carry no tracer
    provenance root, so they contribute through `any_cols` and the `result`
    frames rather than `col_values` — the subtable and join-key scores are
    computed from those anyway.
    """
    df = tables.get(tracer_key) if tracer_key else None
    return df if df is not None else _pd.read_pickle(path)


def _prep(df, spec):
    """Same normalisation the loop applies before and after every step."""
    df = M.sanitize(df)
    return apply_auto_rename(df, plan_next(df, spec)["auto_rename"])


def _apply(df, spec, steps):
    for step in steps:
        df = _prep(M.robust_execute(df, step), spec)
    return df


def _replay(df, steps):
    """`revise_pipeline_code.replay` semantics: sanitize, never auto-rename.

    Deliberately NOT `_apply`. The repair loop reaches a rewritten table through
    that function, and `_apply` additionally applies auto-rename around every
    step, so replaying a rewrite through `_apply` yields different column names
    than the frame that was actually scored.
    """
    df = M.sanitize(df)
    for step in steps or []:
        df = M.sanitize(M.robust_execute(df, step))
    return df


def _rewrite(df, code):
    """Replay a repair-loop `transform(df)` snippet.

    `revise_pipeline` does not emit operators — it has the model write free
    pandas — so a repaired table's provenance is `steps` followed by this. The
    snippet runs on the SAME namespace the loop gave it (pd/np and the frame,
    nothing else) so the replayed frame matches what was scored. No auto-rename
    afterwards: the loop applies none either, and adding one here would rename
    columns the snippet deliberately produced.
    """
    ns = {{"pd": _pd, "np": _np}}
    exec(compile(code, "<rewrite>", "exec"), ns)
    fn = ns.get("transform")
    return fn(df) if fn is not None else df


