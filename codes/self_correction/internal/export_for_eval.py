#!/usr/bin/env python3
"""
export_for_eval.py
==================
Turn synthesized pipelines into the ONE format `eval_all_oom.py` accepts: one
executable Python file per task.

    pipeline_synthesize.py  ->  <pred>_pipelines.jsonl   (ops + params + tables)
    export_for_eval.py      ->  <task_id>.py             (replayable source)

WHY SOURCE AND NOT THE PICKLE
-----------------------------
`eval_all_oom.py` never looks at materialised DataFrames. It loads the raw
inputs itself, then EXECUTES the method's code under a monkeypatched pandas and
reads the metrics off the execution trace:

    ns = {"tables": shared, "input_tables": shared, "pd": pd, "np": np}
    exec(compile(code_src, code_path, "exec"), ns)
    res = ns.get("result")

    col_values / any_cols / prepared   captured from column access + materialisation
    joins                              captured ONLY from pd.merge / DataFrame.merge
                                       / .isin / .map
    result                             read from the global name `result`

Two consequences drive the emitted code:

  * The script MUST call merge on every declared edge. Our pipeline stops at
    subtable synthesis and key repair — it never joins — so without an explicit
    merge the `joins` list stays empty and join-key accuracy scores zero even
    when the keys are perfect.

  * `result` must be set, or `answer_correct` sees None. We emit the produced
    subtables; this is a data-preparation method, so there is no final answer
    table and answer accuracy is not the metric being compared.

FIDELITY
--------
Replaying `steps` alone does NOT reproduce what the loop produced. `run_table`
applies `apply_auto_rename(df, plan_next(df, spec)["auto_rename"])` to the input
frame and again after every step, so the emitted script has to do the same, with
the same spec. That is why each file carries its table spec inline.

Use `--verify` to check this rather than trust it: it replays every exported
script in-process and diffs the resulting column sets against the frames stored
in the run's .pkl.
"""
from __future__ import annotations

import os
