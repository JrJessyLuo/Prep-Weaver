def _load_specs(plan_row: Dict[str, Any]) -> Dict[str, dict]:
    """Rebuild the per-table spec the loop ran with (drives auto_rename)."""
    sys.path.insert(0, str(TRAIN)) if str(TRAIN) not in sys.path else None
    from schema_spec import parse_create_table
    out = {}
    for t in plan_row.get("gold_tables") or []:
        lt = t.get("logical_table")
        schema, pk = parse_create_table(t.get("create_table_sql") or "")
        out[lt] = {"create_table_sql": t.get("create_table_sql") or "",
                   "column_types": schema,
                   "primary_key": sorted(pk),
                   "output_columns": list(schema),
                   "join_cols": sorted(t.get("join_cols") or [])}
    return out


def export_one(pipe: Dict[str, Any], plan: Dict[str, Any], task: Dict[str, Any],
               out_dir: Path, bench_dir: Path = BENCH_DIR) -> Path:
    """Write one task's script.

    Split out of `export` so the repair loop can emit a script for a state it
    holds in memory. A repaired state is the same shape — per-table `steps`
    plus `join_keys` — with `codes` carrying the free-pandas rewrites.
    """
    sys.path.insert(0, str(TRAIN))
    _FILE_TO_TRACER.clear()
    for i, f in enumerate(task.get("input_table") or [], start=1):
        _FILE_TO_TRACER[f] = f"table_{i}"

    input_files = {}
    # The plan's OWN input_file is authoritative. The positional fallback below
    # existed for plans that name a file the task does not list, and on
    # bird/spider that never fired because `input_table` is the whole pool. On
    # beaver the pool is `retrieved_table` (median overlap with input_table .60),
    # so a plan naming a retrieved-only table fell through to the fallback and was
    # paired with WHATEVER sat at that index of input_table: beaver-bcaf9d3f got a
    # room-table schema (BUILDING_KEY, FLOOR_KEY, ROOM_SQUARE_FOOTAGE) bolted onto
    # FCLT_ORGANIZATION_HIST. The steps then cannot produce the declared columns
    # and every declared join edge dies on KeyError — 67 of them across the repair
    # export, dropping join-edge execution from 97% to 76%.
    files = list(task.get("retrieved_table") or task.get("input_table") or [])
    for t in plan.get("gold_tables") or []:
        lt, f = t.get("logical_table"), t.get("input_file")
        if f:
            input_files[lt] = f            # trust the plan, whatever pool it came from
            continue
        idx = int(str(lt).split("_")[1]) - 1
        if 0 <= idx < len(files):
            input_files[lt] = files[idx]

    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"{pipe.get('task_id')}.py"
    p.write_text(render_task(pipe, input_files, _load_specs(plan), bench_dir))
    return p


def export(pipelines_jsonl: Path,
           plans_jsonl: Path,
           out_dir: Path = DEFAULT_OUT,
           bench_dir: Path = BENCH_DIR,
           tasks: Optional[set] = None) -> List[Path]:
    sys.path.insert(0, str(TRAIN))
    import pandas as pd  # noqa: F401  (imported so the project modules resolve)

    bench = {json.loads(l)["task_id"]: json.loads(l)
             for l in (bench_dir / "benchmark.jsonl").open()}
    plans = {json.loads(l)["task_id"]: json.loads(l)
             for l in plans_jsonl.open() if l.strip()}
    out_dir.mkdir(parents=True, exist_ok=True)

    written = []
    for line in pipelines_jsonl.open():
        if not line.strip():
            continue
        pipe = json.loads(line)
        tid = pipe.get("task_id")
        if tasks and tid not in tasks:
            continue
        plan, task = plans.get(tid), bench.get(tid)
        if not plan or not task:
            print(f"  skip {tid}: missing plan or benchmark record", file=sys.stderr)
            continue

        _FILE_TO_TRACER.clear()
        for i, f in enumerate(task.get("input_table") or [], start=1):
            _FILE_TO_TRACER[f] = f"table_{i}"

        input_files = {}
        for t in plan.get("gold_tables") or []:
            lt, f = t.get("logical_table"), t.get("input_file")
            files = task.get("input_table") or []
            if f and f in files:
                input_files[lt] = f
            else:
                idx = int(str(lt).split("_")[1]) - 1
                if 0 <= idx < len(files):
                    input_files[lt] = files[idx]

        src = render_task(pipe, input_files, _load_specs(plan), bench_dir)
        p = out_dir / f"{tid}.py"
        p.write_text(src)
        written.append(p)
    return written


def verify(written: Sequence[Path], run_pkl: Path,
           bench_dir: Path = BENCH_DIR) -> int:
    """Replay each exported script and diff its columns against the stored run.

    Catches the failure mode the whole design turns on: if `auto_rename` or the
    input-file binding is wrong, the replay silently produces different columns
    from the ones the pipeline was scored on, and the external evaluation would
    be measuring something we never validated.
    """
    import pandas as pd
    with run_pkl.open("rb") as fh:
        run = pickle.load(fh)
    bench = {json.loads(l)["task_id"]: json.loads(l)
             for l in (bench_dir / "benchmark.jsonl").open()}
    bad = 0
    for p in written:
        tid = p.stem
        stored = (run.get(tid) or {}).get("subtables") or {}
        tables = {}
        for i, f in enumerate(bench[tid].get("input_table") or [], start=1):
            try:
                tables[f"table_{i}"] = pd.read_pickle(bench_dir / f)
            except Exception:
                pass
        ns = {"tables": tables, "input_tables": tables, "pd": pd}
        try:
            exec(compile(p.read_text(), str(p), "exec"), ns)
        except Exception as exc:
            print(f"  {tid}: REPLAY FAILED {type(exc).__name__}: {exc}")
            bad += 1
            continue
        got = ns.get("result") or {}
        for lt, df in stored.items():
            g = got.get(lt)
            if g is None:
                print(f"  {tid}::{lt}: missing from replay")
                bad += 1
            elif set(map(str, g.columns)) != set(map(str, df.columns)):
                only_replay = set(map(str, g.columns)) - set(map(str, df.columns))
                only_stored = set(map(str, df.columns)) - set(map(str, g.columns))
                print(f"  {tid}::{lt}: column mismatch "
                      f"+{sorted(only_replay)[:4]} -{sorted(only_stored)[:4]}")
                bad += 1
    return bad


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[3])
    ap.add_argument("--pipelines", required=True, type=Path,
                    help="<pred>_pipelines.jsonl from actions/pipeline_synthesize.py")
    ap.add_argument("--plans", required=True, type=Path,
                    help="the relational plans jsonl those pipelines were built from")
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--tasks", default=None, help="comma-separated task_id filter")
    ap.add_argument("--verify", type=Path, default=None, metavar="RUN_PKL",
                    help="replay the exported scripts and diff against this run's .pkl")
    ap.add_argument("--benchmark", default=None,
                    help="which benchmark's dev split the input tables come from. "
                         "The module default is nl2sql-bird, which is silently "
                         "wrong for every other benchmark: the exported script "
                         "carries ABSOLUTE paths to the .pkl files it loads, so a "
                         "spider export built against bird's directory points at "
                         "files that do not exist.")
    ap.add_argument("--bench-dir", type=Path, default=None,
                    help="overrides --benchmark; the dev directory itself")
    args = ap.parse_args(argv)

    bench_dir = args.bench_dir or (AUTOP / args.benchmark / "dev"
                                   if args.benchmark else BENCH_DIR)
    if not (bench_dir / "benchmark.jsonl").exists():
        raise SystemExit(f"no benchmark.jsonl under {bench_dir}\n"
                         f"pass --benchmark <name> or --bench-dir <path>")
    print(f"benchmark dir: {bench_dir}")

    keep = {t.strip() for t in args.tasks.split(",")} if args.tasks else None
    written = export(args.pipelines, args.plans, args.out_dir, tasks=keep,
                     bench_dir=bench_dir)
    print(f"wrote {len(written)} scripts -> {args.out_dir}")

    if args.verify:
        print("\nverifying replay against stored frames…")
        bad = verify(written, args.verify, bench_dir=bench_dir)
        print("all replays match the stored frames" if not bad
              else f"{bad} mismatch(es) — the exported code does NOT reproduce the run")
        return 1 if bad else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
